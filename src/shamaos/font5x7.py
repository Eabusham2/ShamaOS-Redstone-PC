def verilog_source() -> str:
    lines = [
        "// Generated from shamaos.font5x7.FONT5X7; do not hand-edit glyphs.",
        "module shama_font5x7(",
        "    input logic [7:0] ch_in,",
        "    input logic [2:0] row,",
        "    output logic [4:0] bits",
        ");",
        "    logic [34:0] glyph;",
        "    always_comb begin",
        "        glyph=35'd0;",
        "        case(ch_in)",
    ]
    for character, rows in sorted(FONT5X7.items()):
        packed = ''.join(f'{r:05b}' for r in rows)
        lines.append(f"            8'h{character:02x}:glyph=35'b{packed};")
    lines.extend([
        "            default:glyph=35'd0;",
        "        endcase",
        "        bits=(row<7)?glyph[(6-row)*5 +: 5]:5'd0;",
        "    end",
        "endmodule",
        "",
    ])
    return '\n'.join(lines)
